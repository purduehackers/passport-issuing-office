export type PortraitName = keyof typeof ART;

const cache = new Map<PortraitName, string>();

/** A data URL with the portrait as a crisp SVG. */
export function portraitUrl(name: PortraitName) {
  let url = cache.get(name);
  if (!url) {
    const rects = ART[name].flatMap((row, y) =>
      [...row].flatMap((cell, x) => (INK[cell] ? [`<rect x="${x}" y="${y}" width="1" height="1" fill="${INK[cell]}"/>`] : [])),
    );
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 20" shape-rendering="crispEdges">${rects.join("")}</svg>`;
    url = `data:image/svg+xml,${encodeURIComponent(svg)}`;
    cache.set(name, url);
  }
  return url;
}
